// One id per browser tab, sent as X-Client-Id on every API request. Live
// events carry it back as ``origin``, so a tab can skip the echo of its
// own change while another tab of the same person still applies it.
// randomUUID needs a secure context; plain-http deploys get the same shape
// from getRandomValues.

export const CLIENT_ID_HEADER = 'X-Client-Id'

/** A random v4 UUID, in a secure context or not. */
export function newUuid(): string {
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID()
  const bytes = crypto.getRandomValues(new Uint8Array(16))
  bytes[6] = (bytes[6] & 0x0f) | 0x40
  bytes[8] = (bytes[8] & 0x3f) | 0x80
  const hex = Array.from(bytes, b => b.toString(16).padStart(2, '0')).join('')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}

export const clientId = newUuid()
